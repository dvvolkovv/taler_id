-- Время начала текущей попытки расшифровки.
--
-- Расшифровка отвязана от запроса и живёт дольше него, но не дольше процесса:
-- рестарт посреди работы оставлял встречу в status='processing' навсегда, а
-- списанные за неё деньги — невозвращёнными. Четыре такие встречи провисели с
-- марта по сентябрь.
--
-- Отличить брошенную работу от идущей по одному лишь статусу нельзя: на второй
-- app-ноде в этот момент может считаться та же самая встреча. Отметка времени и
-- есть то, чего не хватало, — по ней уборщик видит, что попытка заведомо
-- просрочена, и только тогда закрывает встречу и возвращает предоплату.
--
-- Nullable: у всех прежних строк отметки нет, и это в порядке вещей — уборщик
-- такие не трогает, чтобы не закрыть работу, о начале которой ему неизвестно.
ALTER TABLE "MeetingSummary" ADD COLUMN "transcriptionStartedAt" TIMESTAMP(3);

-- Уборщик ходит по (status, transcriptionStartedAt) раз в четверть часа.
CREATE INDEX "MeetingSummary_status_transcriptionStartedAt_idx"
  ON "MeetingSummary" ("status", "transcriptionStartedAt");
